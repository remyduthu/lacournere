const translatedAttributes = ["alt", "aria-label", "title"]
const languageSwitch = document.querySelector("[data-language-switch]")

// Remember the French version of everything so switching back needs no second dictionary.
const french = new Map()
document.querySelectorAll("[data-i18n]").forEach(element => {
  french.set(element, {html: element.innerHTML})
})
translatedAttributes.forEach(attribute => {
  document.querySelectorAll(`[data-i18n-${attribute}]`).forEach(element => {
    const saved = french.get(element) ?? {}
    saved[attribute] = element.getAttribute(attribute)
    french.set(element, saved)
  })
})

const setLanguage = language => {
  const isEnglish = language === "en"
  document.querySelectorAll("[data-i18n]").forEach(element => {
    element.innerHTML = isEnglish
      ? english[element.dataset.i18n]
      : french.get(element).html
  })
  translatedAttributes.forEach(attribute => {
    document.querySelectorAll(`[data-i18n-${attribute}]`).forEach(element => {
      const key = element.getAttribute(`data-i18n-${attribute}`)
      element.setAttribute(
        attribute,
        isEnglish ? english[key] : french.get(element)[attribute],
      )
    })
  })
  document.documentElement.lang = language

  // The button offers the other language, written in that language.
  languageSwitch.textContent = isEnglish ? "FR" : "EN"
  languageSwitch.lang = isEnglish ? "fr" : "en"
  languageSwitch.setAttribute(
    "aria-label",
    isEnglish ? "Lire en français" : "Read in English",
  )
}

const readSavedLanguage = () => {
  try {
    return localStorage.getItem("language")
  } catch {
    return null
  }
}

// A language picked with the button wins over the browser's language.
// Search engine crawlers report an English browser, so they always get French.
const isCrawler = /bot|crawl|spider/i.test(navigator.userAgent)
const browserLanguage =
  isCrawler || navigator.language.startsWith("fr") ? "fr" : "en"
let currentLanguage = readSavedLanguage() ?? browserLanguage
if (currentLanguage === "en") setLanguage("en")

languageSwitch.addEventListener("click", () => {
  currentLanguage = currentLanguage === "en" ? "fr" : "en"
  setLanguage(currentLanguage)
  try {
    localStorage.setItem("language", currentLanguage)
  } catch {}
})
